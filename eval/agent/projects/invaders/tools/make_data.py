#!/usr/bin/env python3
"""Generates data.slug, the Space Invaders ROM data the game needs, from a
text dump of the annotated disassembly at
https://www.computerarcheology.com/Arcade/SpaceInvaders/Code.html.

Usage: make_data.py <code.txt>

It writes workspace/data.slug, which agents get, and the identical
reference/data.slug, which the reference imports.
"""
import os
import re
import sys

# An address, then its bytes, then a mnemonic, a comment, or the line's end.
LINE = re.compile(r"^([0-9A-F]{4}): ((?:[0-9A-F]{2} )*[0-9A-F]{2})(?: {2,}|\s*;|\s*$)")

# (name, address, length, comment)
REGIONS = [
    ("alienSprites", 0x1C00, 0x60, "Aliens: 3 types x 16 columns, frame 0 at 0, frame 1 at 48 (type A bottom rows, B middle, C top)."),
    ("player", 0x1C60, 16, "The player's cannon, 16 columns."),
    ("playerBlowups", 0x1C70, 32, "The two player explosion pictures, 16 columns each."),
    ("playerShot", 0x1C90, 1, "The player's shot, 1 column."),
    ("playerShotExplosion", 0x1C91, 8, "The player's shot exploding, 8 columns."),
    ("alienExplosion", 0x1CC0, 16, "An alien exploding, 16 columns."),
    ("squigglyShot", 0x1CD0, 12, "Squiggly alien shot: 4 pictures of 3 columns."),
    ("alienShotExplosion", 0x1CDC, 6, "An alien shot exploding, 6 columns."),
    ("plungerShot", 0x1CE2, 12, "Plunger alien shot: 4 pictures of 3 columns."),
    ("rollingShot", 0x1CEE, 12, "Rolling alien shot: 4 pictures of 3 columns."),
    ("columnFireTable", 0x1D00, 21, "Firing columns (1-11): the plunger uses entries 0-15, the squiggly 6-20."),
    ("shield", 0x1D20, 44, "A shield: 22 columns of 2 bytes."),
    ("saucerScoreTable", 0x1D54, 16, "Saucer scores in BCD tens (0x10 is 100 points)."),
    ("saucer", 0x1D64, 24, "The flying saucer, 24 columns."),
    ("saucerExplosion", 0x1D7C, 24, "The saucer exploding, 24 columns."),
    ("alienStartTable", 0x1DA3, 8, "Starting Yr of the reference alien for racks 2 to 9."),
    ("font", 0x1E00, 0x200, "64 characters of 8 columns; see the character codes in the task."),
    ("fleetCounts", 0x1A11, 16, "Alien counts for the fleet sound's delays: the first entry that numAliens is at least selects the delay."),
    ("fleetDelays", 0x1A21, 16, "End-of-screen interrupts between fleet notes, one per fleetCounts entry."),
    ("rom0800", 0x0800, 256, "ROM bytes 0x0800-0x08FF (game code). Bit 0 of entry n picks the saucer's direction after the shot count becomes n."),
    ("messageScoreHeader", 0x1AE4, 28, '" SCORE<1> HI-SCORE SCORE<2> "'),
    ("messagePlayPlayer1", 0x1B70, 14, '"PLAY PLAYER<1>"'),
    ("messageGameOver", 0x1AA6, 10, '"GAME OVER "'),
    ("messageOnly1Player", 0x1ACF, 20, '"ONLY 1PLAYER BUTTON "'),
    ("messagePush", 0x1FF3, 4, '"PUSH"'),
    ("messageCredit", 0x1FA9, 7, '"CREDIT "'),
    ("messageSaucer50", 0x1D94, 3, '" 50"'),
    ("messageSaucer100", 0x1D97, 3, '"100"'),
    ("messageSaucer150", 0x1D9A, 3, '"150"'),
    ("messageSaucer300", 0x1D9D, 3, '"300"'),
]

def main(source):
    memory = {}
    for line in open(source):
        match = LINE.match(line)
        if match:
            address = int(match.group(1), 16)
            for offset, token in enumerate(match.group(2).split()):
                memory.setdefault(address + offset, int(token, 16))
    out = [
        "/**",
        " * Space Invaders ROM data: sprites, the font, tables, and messages, copied",
        " * from the original ROM. Generated by tools/make_data.py; do not edit.",
        " *",
        " * A sprite is a sequence of bytes, one per column (one video-RAM row),",
        " * with bit 0 the lowest pixel.",
        " */",
        "",
    ]
    for name, address, length, comment in REGIONS:
        data = [memory.get(address + i) for i in range(length)]
        missing = [hex(address + i) for i, b in enumerate(data) if b is None]
        if missing:
            sys.exit(f"{name}: missing bytes at {missing[:4]}")
        out.extend(["/**", f" * {comment}", " */"])
        hexes = "".join(f"{b:02x}" for b in data)
        chunks = [hexes[i:i + 64] for i in range(0, len(hexes), 64)]
        if len(chunks) == 1:
            out.append(f'export val {name} = 0x"{chunks[0]}"')
        else:
            out.append(f"export val {name} =")
            out.append("    " + " +\n    ".join(f'0x"{c}"' for c in chunks))
        out.append("")
    project = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    for target in ("workspace/data.slug", "reference/data.slug"):
        open(os.path.join(project, target), "w").write("\n".join(out))

if __name__ == "__main__":
    main(sys.argv[1])
