//! Generates one C translation unit with a uniform-entry shim for every
//! binding. See `docs/decisions/2026-10-10-uniform-shim-entry.md`.
//!
//! Every generated function except the table functions has internal linkage
//! and a `slug_shim_` prefix. Each addressable target and free function is
//! called through an exact-typed function pointer, so the compiler compares
//! the manifest's types with the header's declarations.

use std::fmt::Write as _;

use crate::{
    Binding, Direction, ManifestError, NativeManifest, NativeType, Parameter, SHIM_ABI_VERSION,
    Signature, is_identifier,
};

/// C compiler flags every shim builds with, for clang and gcc.
pub const SHIM_C_FLAGS: &[&str] = &[
    "-std=c11",
    "-Wall",
    "-Wextra",
    "-Wconversion",
    "-Wsign-conversion",
    "-Werror",
];

/// Preprocessor macro that adds the exported `slug_shim_get_table` alias,
/// defined only when the shim is built into a dynamic library.
pub const DYNAMIC_DEFINE: &str = "SLUG_SHIM_DYNAMIC";

/// File name of the producer header the shim build writes beside each shim.
pub const PRODUCER_HEADER_NAME: &str = "slug_producer.h";

/// The producer header: the capability a `producer` argument passes, its host
/// function table, and inline wrappers. See
/// `docs/decisions/2026-10-11-typed-native-producers.md`.
pub const PRODUCER_HEADER: &str = r"/* Generated by slug-native-manifest. Do not edit. */
#ifndef SLUG_PRODUCER_H
#define SLUG_PRODUCER_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#define SLUG_PRODUCER_API_VERSION 1u

/* Send statuses. */
#define SLUG_PRODUCER_SENT 0
#define SLUG_PRODUCER_FULL 1
#define SLUG_PRODUCER_CLOSED 2
#define SLUG_PRODUCER_INVALID 3

typedef struct slug_producer slug_producer;

/* Host functions. Each may be called from any thread and never blocks. Text
 * and bytes are copied; the caller keeps its buffer whatever the status. */
typedef struct slug_producer_api {
  uint32_t version;
  int32_t (*send_nil)(slug_producer *producer);
  int32_t (*send_bool)(slug_producer *producer, bool value);
  int32_t (*send_i64)(slug_producer *producer, int64_t value);
  int32_t (*send_f64)(slug_producer *producer, double value);
  int32_t (*send_text)(slug_producer *producer, const char *text, size_t length);
  int32_t (*send_bytes)(slug_producer *producer, const uint8_t *data, size_t length);
  bool (*is_closed)(slug_producer *producer);
  void (*close)(slug_producer *producer);
  void (*release)(slug_producer *producer);
} slug_producer_api;

/* A producer capability. The host's allocation extends it; release it
 * exactly once and do not use it afterwards. */
struct slug_producer {
  const slug_producer_api *api;
};

static inline int32_t slug_producer_send_nil(slug_producer *producer) {
  return producer->api->send_nil(producer);
}
static inline int32_t slug_producer_send_bool(slug_producer *producer, bool value) {
  return producer->api->send_bool(producer, value);
}
static inline int32_t slug_producer_send_i64(slug_producer *producer, int64_t value) {
  return producer->api->send_i64(producer, value);
}
static inline int32_t slug_producer_send_f64(slug_producer *producer, double value) {
  return producer->api->send_f64(producer, value);
}
static inline int32_t slug_producer_send_text(slug_producer *producer, const char *text,
                                              size_t length) {
  return producer->api->send_text(producer, text, length);
}
static inline int32_t slug_producer_send_bytes(slug_producer *producer, const uint8_t *data,
                                               size_t length) {
  return producer->api->send_bytes(producer, data, length);
}
static inline bool slug_producer_is_closed(slug_producer *producer) {
  return producer->api->is_closed(producer);
}
static inline void slug_producer_close(slug_producer *producer) {
  producer->api->close(producer);
}
static inline void slug_producer_release(slug_producer *producer) {
  producer->api->release(producer);
}

#endif
";

/// Whether any binding of `manifest` takes a `producer` argument.
#[must_use]
pub fn uses_producers(manifest: &NativeManifest) -> bool {
    manifest.bindings().any(|binding| {
        binding
            .signature
            .parameters
            .iter()
            .any(|parameter| parameter.native_type == NativeType::Producer)
    })
}

/// Name of the provider-unique table function for `provider`.
#[must_use]
pub fn table_function(provider: &str) -> String {
    format!("slug_shim_table_{provider}")
}

/// Generates the shim translation unit for `manifest`. `provider` names the
/// table function, `slug_shim_table_<provider>`, and must be a C identifier
/// unique among the shims linked into one image.
///
/// # Errors
///
/// Returns a checked error when `provider` is not a C identifier.
pub fn generate(manifest: &NativeManifest, provider: &str) -> Result<String, ManifestError> {
    if !is_identifier(provider) {
        return Err(ManifestError::new(
            "provider",
            format!("`{provider}` is not a C identifier"),
        ));
    }
    let bindings = manifest.bindings().collect::<Vec<_>>();
    let mut output = String::new();
    output.push_str(PRELUDE);
    if uses_producers(manifest) {
        let _ = writeln!(output, "#include \"{PRODUCER_HEADER_NAME}\"");
    }
    for header in &manifest.headers {
        let _ = writeln!(output, "#include \"{header}\"");
    }
    output.push_str(ABI);
    for (index, binding) in bindings.iter().enumerate() {
        write_entry(&mut output, index, binding);
    }
    write_table(&mut output, &bindings, provider);
    Ok(output)
}

/// Compares an existing shim with what [`generate`] produces now.
///
/// # Errors
///
/// Returns a checked error when `provider` is invalid, or one naming the first
/// differing line when `existing` is stale.
pub fn check(
    manifest: &NativeManifest,
    provider: &str,
    existing: &str,
) -> Result<(), ManifestError> {
    let expected = generate(manifest, provider)?;
    if expected == existing {
        return Ok(());
    }
    let mut expected_lines = expected.lines();
    let mut existing_lines = existing.lines();
    let mut line = 1usize;
    loop {
        match (expected_lines.next(), existing_lines.next()) {
            (Some(left), Some(right)) if left == right => line += 1,
            (expected, existing) => {
                return Err(ManifestError::new(
                    format!("shim line {line}"),
                    format!(
                        "stale shim: expected `{}`, found `{}`",
                        expected.unwrap_or("<end of file>"),
                        existing.unwrap_or("<end of file>")
                    ),
                ));
            }
        }
    }
}

const PRELUDE: &str = "\
/* Generated by slug-native-manifest. Do not edit. */
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <string.h>
";

const ABI: &str = "
typedef struct slug_value {
  union {
    int64_t i64;
    uint64_t u64;
    double f64;
    const void *pointer;
  } as;
  uint64_t length;
} slug_value;

typedef struct slug_shim_cleanup {
  void (*release)(void *context);
  void *context;
} slug_shim_cleanup;

typedef int32_t (*slug_shim_entry)(const slug_value *arguments,
                                   slug_value *results,
                                   slug_shim_cleanup *cleanup);

typedef struct slug_shim_binding {
  const char *module;
  const char *name;
  const char *signature;
  slug_shim_entry entry;
  uint32_t argument_count;
  uint32_t result_count;
} slug_shim_binding;

typedef struct slug_shim_table {
  uint32_t abi_version;
  uint32_t binding_count;
  const slug_shim_binding *bindings;
} slug_shim_table;
";

/// The C type a parameter or result has in the target's declaration.
fn c_type(native_type: &NativeType) -> String {
    match native_type {
        NativeType::Bool => "bool".into(),
        NativeType::I8 => "int8_t".into(),
        NativeType::I16 => "int16_t".into(),
        NativeType::I32 => "int32_t".into(),
        NativeType::I64 => "int64_t".into(),
        NativeType::U8 => "uint8_t".into(),
        NativeType::U16 => "uint16_t".into(),
        NativeType::U32 => "uint32_t".into(),
        NativeType::U64 => "uint64_t".into(),
        NativeType::F32 => "float".into(),
        NativeType::F64 => "double".into(),
        NativeType::Str { owned: None } | NativeType::Cstr { owned: None } => "const char *".into(),
        NativeType::Str { owned: Some(_) } | NativeType::Cstr { owned: Some(_) } => "char *".into(),
        NativeType::Bytes { owned: None } => "const uint8_t *".into(),
        NativeType::Bytes { owned: Some(_) } => "uint8_t *".into(),
        NativeType::Handle { c_type, .. } => format!("{c_type} *"),
        NativeType::Producer => "slug_producer *".into(),
    }
}

/// The C parameter types of one manifest parameter: `str` and `bytes` pass a
/// pointer and a `size_t` length, and `out` passes a pointer to each.
fn c_parameter_types(parameter: &Parameter) -> Vec<String> {
    let base = c_type(&parameter.native_type);
    let length_delimited = matches!(
        parameter.native_type,
        NativeType::Str { .. } | NativeType::Bytes { .. }
    );
    match (parameter.direction, length_delimited) {
        (Direction::Out, true) => vec![pointer_to(&base), "size_t *".into()],
        (Direction::Out, false) => vec![pointer_to(&base)],
        (_, true) => vec![base, "size_t".into()],
        (_, false) => vec![base],
    }
}

/// The free function of an owned text or bytes result.
fn owned_free(native_type: &NativeType) -> Option<&str> {
    match native_type {
        NativeType::Cstr { owned } | NativeType::Str { owned } | NativeType::Bytes { owned } => {
            owned.as_deref()
        }
        _ => None,
    }
}

fn pointer_to(base: &str) -> String {
    if base.ends_with('*') {
        format!("{base}*")
    } else {
        format!("{base} *")
    }
}

fn declarator(base: &str, name: &str) -> String {
    if base.ends_with('*') {
        format!("{base}{name}")
    } else {
        format!("{base} {name}")
    }
}

/// The C expression that reads argument cell `cell` as `native_type`.
fn argument_expression(native_type: &NativeType, cell: usize) -> Vec<String> {
    let value = format!("arguments[{cell}].as");
    match native_type {
        NativeType::Bool => vec![format!("{value}.u64 != 0u")],
        NativeType::I64 => vec![format!("{value}.i64")],
        NativeType::U64 => vec![format!("{value}.u64")],
        NativeType::I8 | NativeType::I16 | NativeType::I32 => {
            vec![format!("({}){value}.i64", c_type(native_type))]
        }
        NativeType::U8 | NativeType::U16 | NativeType::U32 => {
            vec![format!("({}){value}.u64", c_type(native_type))]
        }
        NativeType::F32 => vec![format!("(float){value}.f64")],
        NativeType::F64 => vec![format!("{value}.f64")],
        NativeType::Str { .. } | NativeType::Bytes { .. } => vec![
            format!("({}){value}.pointer", c_type(native_type)),
            format!("(size_t)arguments[{cell}].length"),
        ],
        NativeType::Cstr { .. } | NativeType::Handle { .. } | NativeType::Producer => {
            vec![format!("({}){value}.pointer", c_type(native_type))]
        }
    }
}

/// Statements that store `value` of `native_type` in result cell `cell`. A
/// length-delimited `out` value stores the length the callee wrote to
/// `<value>_length`.
fn store_result(output: &mut String, native_type: &NativeType, value: &str, cell: usize) {
    let target = format!("results[{cell}]");
    match native_type {
        NativeType::Bool => {
            let _ = writeln!(output, "  {target}.as.u64 = {value} ? 1u : 0u;");
        }
        NativeType::I8 | NativeType::I16 | NativeType::I32 | NativeType::I64 => {
            let _ = writeln!(output, "  {target}.as.i64 = (int64_t){value};");
        }
        NativeType::U8 | NativeType::U16 | NativeType::U32 | NativeType::U64 => {
            let _ = writeln!(output, "  {target}.as.u64 = (uint64_t){value};");
        }
        NativeType::F32 | NativeType::F64 => {
            let _ = writeln!(output, "  {target}.as.f64 = (double){value};");
        }
        NativeType::Cstr { .. } => {
            let _ = writeln!(output, "  {target}.as.pointer = {value};");
            let _ = writeln!(
                output,
                "  {target}.length = {value} ? (uint64_t)strlen({value}) : 0u;"
            );
            return;
        }
        NativeType::Str { .. } | NativeType::Bytes { .. } => {
            let _ = writeln!(output, "  {target}.as.pointer = {value};");
            let _ = writeln!(
                output,
                "  {target}.length = {value} ? (uint64_t){value}_length : 0u;"
            );
            return;
        }
        // A producer is never a result; validation rejects it.
        NativeType::Handle { .. } | NativeType::Producer => {
            let _ = writeln!(output, "  {target}.as.pointer = {value};");
        }
    }
    let _ = writeln!(output, "  {target}.length = 0u;");
}

fn zero_value(native_type: &NativeType) -> &'static str {
    match native_type {
        NativeType::Bool => "false",
        NativeType::F32 | NativeType::F64 => "0.0",
        NativeType::Str { .. }
        | NativeType::Bytes { .. }
        | NativeType::Cstr { .. }
        | NativeType::Handle { .. }
        | NativeType::Producer => "NULL",
        _ => "0",
    }
}

fn entry_name(index: usize, binding: &Binding) -> String {
    format!("slug_shim_{index}_{}", binding.name.replace(':', "_"))
}

/// Declares the exact-typed pointer to an addressable target and returns the
/// expression the entry calls.
fn write_target(output: &mut String, entry: &str, binding: &Binding) -> String {
    if binding.is_macro {
        return binding.symbol.clone();
    }
    let signature = &binding.signature;
    let result_type = signature
        .result
        .as_ref()
        .map_or_else(|| "void".to_owned(), c_type);
    let parameter_types = signature
        .parameters
        .iter()
        .flat_map(c_parameter_types)
        .collect::<Vec<_>>();
    let parameter_list = if parameter_types.is_empty() {
        "void".to_owned()
    } else {
        parameter_types.join(", ")
    };
    let target = format!("{entry}_target");
    let _ = writeln!(
        output,
        "static {result_type} (*const {target})({parameter_list}) = {};",
        binding.symbol
    );
    target
}

/// Emits the release function for owned text results, with an exact-typed
/// check of each free function. Returns whether the entry sets cleanup.
fn write_release(output: &mut String, entry: &str, signature: &Signature) -> bool {
    // (result cell, free function) for each owned result.
    let mut owned = Vec::new();
    if let Some(free) = signature.result.as_ref().and_then(owned_free) {
        owned.push((0, free));
    }
    let first_out_cell = usize::from(signature.result.is_some());
    let outs = signature
        .parameters
        .iter()
        .filter(|parameter| parameter.direction == Direction::Out);
    for (offset, parameter) in outs.enumerate() {
        if let Some(free) = owned_free(&parameter.native_type) {
            owned.push((first_out_cell + offset, free));
        }
    }
    if owned.is_empty() {
        return false;
    }
    let mut frees = Vec::<&str>::new();
    for (_, free) in &owned {
        if !frees.contains(free) {
            frees.push(free);
        }
    }
    for (free_index, free) in frees.iter().enumerate() {
        let _ = writeln!(
            output,
            "static void (*const {entry}_free_{free_index})(void *) = {free};"
        );
    }
    let _ = writeln!(output, "static void {entry}_release(void *context) {{");
    let _ = writeln!(output, "  slug_value *results = context;");
    for (cell, free) in &owned {
        let free_index = frees
            .iter()
            .position(|candidate| candidate == free)
            .unwrap_or_default();
        let _ = writeln!(
            output,
            "  if (results[{cell}].as.pointer != NULL) {entry}_free_{free_index}((void *)results[{cell}].as.pointer);"
        );
    }
    let _ = writeln!(output, "}}");
    true
}

fn write_entry(output: &mut String, index: usize, binding: &Binding) {
    let entry = entry_name(index, binding);
    let signature = &binding.signature;
    let _ = writeln!(output, "\n/* {} */", binding.canonical_signature());
    let callee = write_target(output, &entry, binding);
    let sets_cleanup = write_release(output, &entry, signature);
    let first_out_cell = usize::from(signature.result.is_some());
    let outs = signature
        .parameters
        .iter()
        .filter(|parameter| parameter.direction == Direction::Out)
        .collect::<Vec<_>>();

    let _ = writeln!(
        output,
        "static int32_t {entry}(const slug_value *arguments, slug_value *results, slug_shim_cleanup *cleanup) {{"
    );
    let mut call_arguments = Vec::new();
    let mut argument_cell = 0usize;
    let mut out_index = 0usize;
    for parameter in &signature.parameters {
        if parameter.direction == Direction::Out {
            let local = format!("out_{out_index}");
            let _ = writeln!(
                output,
                "  {} = {};",
                declarator(&c_type(&parameter.native_type), &local),
                zero_value(&parameter.native_type)
            );
            call_arguments.push(format!("&{local}"));
            if matches!(
                parameter.native_type,
                NativeType::Str { .. } | NativeType::Bytes { .. }
            ) {
                let _ = writeln!(output, "  size_t {local}_length = 0;");
                call_arguments.push(format!("&{local}_length"));
            }
            out_index += 1;
        } else {
            call_arguments.extend(argument_expression(&parameter.native_type, argument_cell));
            argument_cell += 1;
        }
    }
    if argument_cell == 0 {
        let _ = writeln!(output, "  (void)arguments;");
    }
    if signature.result_cells() == 0 {
        let _ = writeln!(output, "  (void)results;");
    }
    if !sets_cleanup {
        let _ = writeln!(output, "  (void)cleanup;");
    }
    let call = format!("{callee}({})", call_arguments.join(", "));
    match &signature.result {
        Some(result) => {
            let _ = writeln!(
                output,
                "  {} = {call};",
                declarator(&c_type(result), "value")
            );
            store_result(output, result, "value", 0);
        }
        None => {
            let _ = writeln!(output, "  {call};");
        }
    }
    for (offset, parameter) in outs.iter().enumerate() {
        store_result(
            output,
            &parameter.native_type,
            &format!("out_{offset}"),
            first_out_cell + offset,
        );
    }
    if sets_cleanup {
        let _ = writeln!(output, "  cleanup->release = {entry}_release;");
        let _ = writeln!(output, "  cleanup->context = results;");
    }
    let _ = writeln!(output, "  return 0;\n}}");
}

fn write_table(output: &mut String, bindings: &[&Binding], provider: &str) {
    let table_function = table_function(provider);
    output.push('\n');
    if bindings.is_empty() {
        let _ = writeln!(
            output,
            "static const slug_shim_table slug_shim_table_data = {{{SHIM_ABI_VERSION}u, 0u, NULL}};"
        );
    } else {
        let _ = writeln!(
            output,
            "static const slug_shim_binding slug_shim_bindings[] = {{"
        );
        for (index, binding) in bindings.iter().enumerate() {
            let _ = writeln!(
                output,
                "  {{\"{}\", \"{}\", \"{}\", {}, {}u, {}u}},",
                binding.module,
                binding.name,
                binding.canonical_signature(),
                entry_name(index, binding),
                binding.signature.argument_cells(),
                binding.signature.result_cells()
            );
        }
        let _ = writeln!(output, "}};");
        let _ = writeln!(
            output,
            "static const slug_shim_table slug_shim_table_data = {{{SHIM_ABI_VERSION}u, {}u, slug_shim_bindings}};",
            bindings.len()
        );
    }
    let _ = write!(
        output,
        "
const slug_shim_table *{table_function}(void);
const slug_shim_table *{table_function}(void) {{ return &slug_shim_table_data; }}

#if defined({DYNAMIC_DEFINE})
#if defined(_WIN32)
#define SLUG_SHIM_EXPORT __declspec(dllexport)
#else
#define SLUG_SHIM_EXPORT __attribute__((visibility(\"default\")))
#endif
SLUG_SHIM_EXPORT const slug_shim_table *slug_shim_get_table(void);
SLUG_SHIM_EXPORT const slug_shim_table *slug_shim_get_table(void) {{ return &slug_shim_table_data; }}
#endif
"
    );
}
