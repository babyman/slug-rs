"""Writes modules/data.slug, the tables slug.text.markdown looks characters up in.

    python3 -I tools/generate.py entities.json > modules/data.slug

`entities.json` is the WHATWG list of HTML named character references
(https://html.spec.whatwg.org/entities.json). Punctuation and case folding
come from this Python's `unicodedata`, whose Unicode version the output
names.
"""

import json
import sys
import unicodedata


def slug_string(text):
    out = []
    for c in text:
        if c in '\\"$':
            out.append("\\" + c)
        elif ord(c) < 0x20 or ord(c) == 0x7F:
            out.append("\\%03o" % ord(c))
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def ranges(predicate):
    found = []
    start = None
    for code in range(0x80, 0x110000):
        hit = predicate(chr(code))
        if hit and start is None:
            start = code
        elif not hit and start is not None:
            found.append((start, code - 1))
            start = None
    if start is not None:
        found.append((start, 0x10FFFF))
    return found


def main():
    with open(sys.argv[1], encoding="utf-8") as f:
        entities = json.load(f)
    named = sorted((name[1:-1], value["characters"]) for name, value in entities.items() if name.endswith(";"))

    punctuation = ranges(lambda c: unicodedata.category(c)[0] in "PS")
    folds = []
    for code in range(0x80, 0x110000):
        c = chr(code)
        if unicodedata.category(c) in ("Cs", "Cn"):
            continue
        folded = c.casefold()
        if folded != c:
            folds.append((c, folded))

    w = sys.stdout.write
    w("// Generated by tools/generate.py from the WHATWG entities.json and\n")
    w("// Unicode %s; do not edit.\n\n" % unicodedata.unidata_version)
    w("// HTML named character references, without their `&` and `;`.\n")
    w("export val ENTITIES = {\n")
    for name, chars in named:
        w("    %s: %s,\n" % (slug_string(name), slug_string(chars)))
    w("}\n\n")
    w("// Non-ASCII code points in the Unicode P and S categories, as sorted,\n")
    w("// inclusive [first, last] ranges.\n")
    w("export val PUNCTUATION = [\n")
    for first, last in punctuation:
        w("    [%d, %d],\n" % (first, last))
    w("]\n\n")
    w("// Non-ASCII characters whose full Unicode case folding differs from\n")
    w("// them, mapped to their folding.\n")
    w("export val FOLDS = {\n")
    for c, folded in folds:
        w("    %s: %s,\n" % (slug_string(c), slug_string(folded)))
    w("}\n")


main()
